export function t(key) {
    const dictionary = UI_TEXT[SCHEMA_LANGUAGE] || UI_TEXT.en;
    return dictionary[key] || UI_TEXT.en[key] || key;
}

// Apply the current language to the marked-up HTML.
//
// `index.html` carries `data-i18n` on the element whose **entire** content is
// the text -- which is why `textContent` can be rewritten without erasing any
// icon. Where the text shares the element with an `<i>`, the markup sits on a
// `<span>` holding only the text.
//
// Until this slice the index's ~93 texts were hard-coded English, and only the
// forms translated (their labels come from the backend). The language selector
// did not exist: `preferredLanguage()` read a `localStorage` that nothing in the
// interface could write -- dead configuration deciding what the user saw.
export function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(node => {
        node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(node => {
        node.setAttribute('title', t(node.dataset.i18nTitle));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
        node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
    });
    document.querySelectorAll('select.ui-language').forEach(selector => {
        selector.value = SCHEMA_LANGUAGE;
    });
}

// The current language. It existed as `idiomaDoSchema`, was removed for having
// no consumer, and comes back now because the help has to choose between two
// blocks of text -- and a block of HTML does not fit in a dictionary of keys.
export function currentLanguage() {
    return SCHEMA_LANGUAGE;
}

export function preferredLanguage() {
    try {
        return localStorage.getItem('ross-language') || 'en';
    } catch (e) {
        return 'en';   // navegador com storage bloqueado
    }
}

export function rememberLanguage(language) {
    try {
        localStorage.setItem('ross-language', language);
    } catch (e) { /* preferencia e conveniencia, nao pode quebrar a interface */ }
}
