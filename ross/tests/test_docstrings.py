def public_methods(cls, prefix=""):
    return [
        getattr(cls, name)
        for name in dir(cls)
        if not name.startswith("_")
        and name.startswith(prefix)
        and callable(getattr(cls, name))
        and getattr(cls, name).__doc__
    ]


def own_methods(cls):
    """Return the documented public methods defined in ``cls`` itself."""
    return [
        getattr(cls, name)
        for name in vars(cls)
        if not name.startswith("_")
        and callable(getattr(cls, name))
        and getattr(cls, name).__doc__
    ]


