"""Check the docstrings of the analysis API, as the API reference renders them.

The checks cover every ``Rotor.run_*`` method and the motor classes, whose
pages are generated by numpydoc and Sphinx. A docstring that breaks the
reStructuredText markup renders with misplaced text and adds errors to the
documentation build.
"""

import importlib
import inspect
import re

import pytest

from ross import MotorElement, Rotor, motor_example
from ross.motors.motor_drive import InverterFOC, InverterVF, SourceAC
from ross.motors.results import MotorResponseResults, PhaseResults


def public_methods(cls, prefix=""):
    return [
        getattr(cls, name)
        for name in dir(cls)
        if not name.startswith("_")
        and name.startswith(prefix)
        and callable(getattr(cls, name))
        and getattr(cls, name).__doc__
    ]


MOTOR_CLASSES = [
    MotorElement,
    MotorResponseResults,
    PhaseResults,
    SourceAC,
    InverterVF,
    InverterFOC,
]
DOCUMENTED = [
    *public_methods(Rotor, prefix="run_"),
    motor_example,
    *MOTOR_CLASSES,
    *[method for cls in MOTOR_CLASSES for method in public_methods(cls)],
]


def rst_problems(obj):
    """Return the docutils warnings and errors of a numpydoc docstring.

    Sphinx-only roles and directives are registered as no-ops, so only the
    reStructuredText markup itself is checked.
    """
    docscrape_sphinx = pytest.importorskip("numpydoc.docscrape_sphinx")
    from docutils import nodes
    from docutils.core import publish_doctree
    from docutils.parsers.rst import Directive, directives, roles

    class SphinxOnlyDirective(Directive):
        has_content = True
        optional_arguments = 1
        final_argument_whitespace = True

        def run(self):
            return []

    text = str(docscrape_sphinx.SphinxDocString(inspect.getdoc(obj)))
    for role in set(re.findall(r":([\w:]+):`", text)):
        roles.register_generic_role(role, nodes.literal)
    for directive in ("seealso", "only"):
        directives.register_directive(directive, SphinxOnlyDirective)
    tree = publish_doctree(
        text, settings_overrides={"report_level": 5, "halt_level": 5}
    )
    return [
        message.astext()
        for message in tree.findall(nodes.system_message)
        if message["level"] >= 2
    ]


def resolve(target):
    parts = target.split(".")
    for i in range(len(parts), 0, -1):
        try:
            obj = importlib.import_module(".".join(parts[:i]))
        except ImportError:
            continue
        for attr in parts[i:]:
            obj = getattr(obj, attr)
        return obj


@pytest.mark.parametrize("obj", DOCUMENTED, ids=lambda obj: obj.__qualname__)
def test_docstring_renders_without_rst_errors(obj):
    assert rst_problems(obj) == []


@pytest.mark.parametrize("obj", DOCUMENTED, ids=lambda obj: obj.__qualname__)
def test_docstring_cross_references_resolve(obj):
    targets = re.findall(r":py:\w+:`~?(ross\.[\w.]+)`", inspect.getdoc(obj))
    unresolved = []
    for target in targets:
        try:
            resolve(target)
        except AttributeError:
            unresolved.append(target)
    assert unresolved == []
