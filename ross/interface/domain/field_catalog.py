# -*- coding: utf-8 -*-
"""Editorial catalog of each element's fields.

Generated from the curation that used to be embedded in app.js's FormTemplates:
field order, label, and what counts as basic or advanced. That is engineering
judgement and does not derive from introspection -- which is why it lives here.

What is NOT here, because domain/schema.py derives it at runtime:
  - whether the parameter exists, and its default -> inspect.signature of the ROSS class
  - the help text                                 -> the class's numpydoc docstring
  - the unit and its alternatives                 -> domain/units.py
"""


def F(
    name,
    label_en,
    label_pt,
    group="main",
    section=None,
    control="text",
    options=None,
    optional=False,
    placeholder=None,
    is_dict=False,
    part_of=None,
):
    """Describe one form field.

    `part_of` is `(parameter, key)` for a field that is one key of a
    dictionary parameter of ROSS -- the hybrid seal's stages: the form shows
    the key as a field of its own, and domain/seal_stages.py puts the
    dictionary back together for ROSS.
    """
    return {
        "name": name,
        "label": {"en": label_en, "pt": label_pt},
        "group": group,
        "section": section,
        "control": control,
        "options": options,
        "optional": optional,
        "placeholder": placeholder,
        "is_dict": is_dict,
        "part_of": part_of,
    }


