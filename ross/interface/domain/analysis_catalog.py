def default_params(analysis):
    """The values a card is born with -- and what the user sees first.

    Including the tables (probes, forces, unbalances): a card is born with one
    row in each, and sending `[]` instead measures something else. In the first
    version of the conversion probe I sent `[]`, and that produced two false
    results: `freq_response` blew up on all three models (the loop over
    input/output pairs did not run) and `time_response` came out "NO EFFECT" on
    both (with no force the response is zero, and zero is zero at any number of
    degrees of freedom).

    It lives here, and not in whoever needs it, because two callers need it now:
    the probe in `tools/` and the executable's self-test.
    """
    return {field["id"]: field.get("val") for field in ANALYSES[analysis]}


def plot_parameters(analysis):
    """Return the fields the computation may not read. Replaces PLOT_PARAMS.

    `interface` roles are included: Campbell's `plot_type` is this guard's
    original defect -- it took part in the computation without entering the
    cache key, so opening Mode Shape and going back to Default returned a
    15-point diagram with the form still saying 50.
    """
    return tuple(c["id"] for c in ANALYSES.get(analysis, ()) if c["role"] != "compute")
