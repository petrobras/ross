def title(analysis, language="en"):
    names = TITLES.get(analysis)
    if not names:
        return analysis.upper()
    return names.get(language) or names["en"]


def titles(language="en"):
    return {name: title(name, language) for name in ANALYSES}


def fields(analysis, language="en"):
    """Return an analysis's fields, with the label already in the language asked."""
    output = []
    for field in ANALYSES.get(analysis, ()):
        copy_of = dict(field)
        copy_of["label"] = field["label"].get(language) or field["label"]["en"]
        output.append(copy_of)
    return output


def catalog(language="en"):
    """Return every analysis, ready to become JSON."""
    return {name: fields(name, language) for name in ANALYSES}


